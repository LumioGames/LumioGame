const error=(code,message)=>Object.assign(new Error(code+': '+message),{code,exitCode:2});
const exactKeys=(obj,keys)=>obj!==null&&typeof obj==='object'&&!Array.isArray(obj)&&
  JSON.stringify(Object.keys(obj).sort())===JSON.stringify([...keys].sort());
export function requireV15Review(files,review=V15_REVIEW) {
  if(!exactKeys(review,['schema','reviewStatus','reviewEvidence','author','generated'])||
      review.schema!=='bomber-v15-traversal-favorite-regions-candidate'||review.reviewStatus!=='accepted-nonauthor'||
      typeof review.reviewEvidence!=='string'||!review.reviewEvidence.length)
    throw error('v15_review_required','Exact nonauthor-reviewed source and official generated bytes are required');
  for(const [name,paths] of [['author',V15_AUTHOR_PATHS],['generated',V15_GENERATED_PATHS]]) {
    if(!exactKeys(review[name],paths))throw error('v15_review_inventory','Closed '+name+' path set differs');
    for(const path of paths) {
      const expected=review[name][path],bytes=files.get(path);
      if(!/^[a-f0-9]{64}$/.test(expected??'')||!Buffer.isBuffer(bytes)||
          createHash('sha256').update(bytes).digest('hex')!==expected)
        throw error('v15_review_bytes','Unreviewed '+path);
    }
  }
  return review;
}
