import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from '../../../.run/browser-tools/node_modules/playwright/index.mjs'

const output = new URL('../../../.run/player-input-evidence/', import.meta.url)
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const results = []
try {
  for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }, { width: 844, height: 390 }, { width: 320, height: 568 }]) {
    const mobile = viewport.width !== 1440
    const page = await browser.newPage({ viewport, hasTouch: mobile })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', msg => { if (msg.type() === 'error') errors.push(`${msg.text()} ${msg.location().url}`) })
    await page.addInitScript(() => localStorage.setItem('lumio-101-bomber-character', 'duck'))
    await page.goto('http://127.0.0.1:5199/tests/player-input.html')
    await page.waitForFunction(() => window.playerInputFixture && document.querySelectorAll('[data-mode="start"] .sel-portrait').length === 5)
    const initial = page.locator('.hud-select[data-mode="start"]')
    const selected = () => initial.locator('.sel-card[aria-checked="true"]').getAttribute('data-character')
    assert.equal(await selected(), 'duck', 'remember last confirmed selection')
    assert.equal(await initial.locator('.sel-card').count(), 5)
    await page.screenshot({ path: fileURLToPath(new URL(`selection-${viewport.width}x${viewport.height}.png`, output)) })
    const layout = await page.evaluate(() => {
      const title = document.querySelector('[data-mode="start"] .sel-title').getBoundingClientRect()
      const go = document.querySelector('[data-mode="start"] .sel-go').getBoundingClientRect()
      return { width: innerWidth, scrollWidth: document.documentElement.scrollWidth, titleTop: title.top, goBottom: go.bottom }
    })
    assert.equal(layout.width, layout.scrollWidth)
    assert.ok(layout.titleTop >= 0, `selection title clipped: ${JSON.stringify(layout)}`)
    // The selector owns Space/WASD while open; these cannot send game input.
    await page.keyboard.press('ArrowRight')
    assert.notEqual(await selected(), 'duck')
    assert.deepEqual(await page.evaluate(() => window.playerInputFixture.commands), [])
    if (viewport.width === 320) {
      await page.keyboard.press('Digit5')
      assert.equal(await selected(), 'kangaroo')
      const fifth = await initial.locator('[data-character="kangaroo"]').boundingBox()
      assert.ok(fifth.y >= 0 && fifth.y + fifth.height <= viewport.height, 'keyboard selection must scroll the fifth card into view')
      await page.screenshot({ path: fileURLToPath(new URL('selection-320x568-scrolled.png', output)) })
    }
    if (!mobile) {
      await page.evaluate(() => { window.playerInputFixture.sendSuccess = false })
      await initial.locator('.sel-go').click()
      assert.deepEqual(await page.evaluate(() => window.playerInputFixture.selections), [])
      assert.equal(await page.evaluate(() => localStorage.getItem('lumio-101-bomber-character')), 'duck')
      await page.evaluate(() => { window.playerInputFixture.sendSuccess = true; window.playerInputFixture.presentation.setSelectionWindow(true, true) })
      await initial.waitFor()
    }
    await initial.locator('[data-character="cat"]').click()
    await initial.locator('.sel-go').click()
    assert.deepEqual(await page.evaluate(() => window.playerInputFixture.selections), ['cat'])
    assert.equal(await page.evaluate(() => localStorage.getItem('lumio-101-bomber-character')), 'cat')
    assert.equal(await initial.isVisible(), false)
    assert.equal(await page.evaluate(() => window.playerInputFixture.presentation.inputBlocked()), false)
    assert.equal(await page.evaluate(() => window.playerInputFixture.snapshot.Players[0].skills.character), 'rabbit', 'selection must not write authoritative snapshot')
    await page.keyboard.down('d')
    await page.waitForTimeout(120)
    await page.keyboard.up('d')
    assert.ok(await page.evaluate(() => window.playerInputFixture.commands.some(c => c[0] === 'move' && c[1] === 2)))
    if (mobile) {
      await page.locator('.touch-root.is-touch:not(.is-blocked)').waitFor()
      const bomb = await page.locator('.tc-bomb').boundingBox()
      const skill = await page.locator('.tc-skill').boundingBox()
      assert.equal(bomb.width, 88)
      assert.equal(skill.width, 68)
      const stick = await page.locator('.tc-stick').boundingBox()
      assert.ok(stick.x + stick.width <= skill.x, 'idle stick and skill button must not overlap')
      assert.ok(skill.x + skill.width <= bomb.x, 'skill and bomb must not overlap')
      const cdp = await page.context().newCDPSession(page)
      const touch = (type, touchPoints) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints })
      const point = (id, x, y) => ({ id, x, y, radiusX: 4, radiusY: 4, force: 1 })
      const origin = point(1, 80, viewport.height - 94)
      const moving = point(1, 124, viewport.height - 124)
      await touch('touchStart', [origin])
      await touch('touchMove', [moving])
      await page.waitForTimeout(120)
      assert.ok(await page.evaluate(() => window.playerInputFixture.commands.some(c => c[0] === 'move' && c[1] === 2 && c[2] === 1)))
      await touch('touchStart', [moving, point(2, bomb.x + 44, bomb.y + 44)])
      await page.waitForTimeout(100)
      await touch('touchEnd', [moving])
      await touch('touchEnd', [])
      assert.equal(await page.evaluate(() => window.playerInputFixture.commands.filter(c => c[0] === 'bomb').length), 1)
      const count = await page.evaluate(() => window.playerInputFixture.commands.length)
      await page.waitForTimeout(150)
      assert.equal(await page.evaluate(() => window.playerInputFixture.commands.length), count, 'release stops cadence')
      assert.deepEqual(await page.evaluate(() => window.playerInputFixture.directions.at(-1)), [0, 0])
      await page.touchscreen.tap(skill.x + 34, skill.y + 34)
      assert.equal(await page.evaluate(() => window.playerInputFixture.commands.filter(c => c[0] === 'skill').length), 1)
      await page.evaluate(() => window.playerInputFixture.pushSkill({ cdFromTick: 100, cdUntilTick: 400 }))
      await page.waitForFunction(() => document.querySelector('.tc-skill').disabled)
      await page.touchscreen.tap(skill.x + 34, skill.y + 34)
      assert.equal(await page.evaluate(() => window.playerInputFixture.commands.filter(c => c[0] === 'skill').length), 1)
      await page.screenshot({ path: fileURLToPath(new URL(`touch-${viewport.width}x${viewport.height}.png`, output)) })
      const overlaps = await page.evaluate(() => {
        const boxes = ['.hud-board', '.hud-stats', '.hud-skills', '.hud-buttons', '.tc-bomb', '.tc-skill'].map(selector => [selector, document.querySelector(selector).getBoundingClientRect()])
        return boxes.flatMap(([a, x], i) => boxes.slice(i + 1).filter(([, y]) => x.left < y.right && y.left < x.right && x.top < y.bottom && y.top < x.bottom).map(([b]) => [a, b]))
      })
      assert.deepEqual(overlaps, [], 'HUD and actionable touch controls must not occlude one another')
      await page.evaluate(() => { window.playerInputFixture.ready = false })
      await page.locator('.touch-root.is-blocked').waitFor({ state: 'attached' })
      await page.evaluate(() => { window.playerInputFixture.ready = true })
    }
    await page.getByRole('button', { name: '设置', exact: true }).click()
    assert.equal(await page.evaluate(() => window.playerInputFixture.presentation.inputBlocked()), true)
    const before = await page.evaluate(() => window.playerInputFixture.commands.length)
    await page.keyboard.press('Space')
    assert.equal(await page.evaluate(() => window.playerInputFixture.commands.length), before)
    await page.getByRole('button', { name: '关闭', exact: true }).click()
    await page.getByRole('button', { name: '换角色', exact: true }).click()
    await page.locator('[data-mode="switch"].is-on').waitFor()
    await page.evaluate(() => window.playerInputFixture.presentation.setSelectionWindow(false, false))
    assert.equal(await page.locator('[data-mode="switch"]').isVisible(), false, 'server closes the allowed selection window')
    await page.evaluate(() => { window.playerInputFixture.dispose(); window.playerInputFixture.dispose() })
    assert.equal(await page.locator('#stage canvas, .hud-layer, .touch-root, .player-label').count(), 0)
    assert.deepEqual(errors, [])
    results.push({ viewport, selectionCards: 5, restored: 'duck', submitted: 'cat', nativeTouch: mobile, layout, errors })
    await page.close()
  }
  await writeFile(new URL('verification.json', output), JSON.stringify({ fixtureOnly: true, scenarios: results }, null, 2))
  console.log(JSON.stringify(results, null, 2))
} finally { await browser.close() }
